 * the upgrade, which the old code DERIVED as `position -> department -> area`:
 *
 *   - a position under an AREA-level department reached that one area, and
 *     its holders belonged to that department;
 *   - a position under an ORGANIZATION-level department reached every area,
 *     and its holders belonged to that department;
 *   - a position under NO department, and a person holding no position,
 *     reached every area and belonged to no department - so they are placed
 *     across the organization and across all departments, which is what the
 *     voter already answered for them.
 *
 * Nobody gains or loses a permission in this migration. What changes is where
 * the answer is stored.
 *
 * DUPLICATE NAMES ARE RENAMED, NOT REFUSED. `Analyst` in Ecology and
 * `Analyst` in Protection were two legal rows and are now one name twice, so
 * the second and any further one take a numeric suffix and the migration
 * RAISES A NOTICE naming each: an administrator reads the rename in the
 * upgrade output and renames them into the organization's own words. Refusing
 * the migration instead would leave an installation unable to upgrade over a
 * row it was told to write.
 *
 * @destructive 1.0 - team_position.department_id and the department-scoped
 *              name index are dropped here, in the same release that stops
 *              reading them: a position carries no department in any code
 *              path after this version, the column would be unmapped, and an
