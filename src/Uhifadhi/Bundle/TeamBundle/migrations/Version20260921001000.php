/**
 * A DEPARTMENT IS A PLACEMENT, NOT AN OWNER.
 *
 * Three facts move at once, because they are one fact: a position stops
 * carrying a department, its name becomes unique across the organization, and
 * where somebody may work becomes a row of their own rather than something
 * derived through their job title.
 *
 * EXPAND, BACKFILL, CONTRACT, IN THIS ORDER. Every column that ends up NOT
